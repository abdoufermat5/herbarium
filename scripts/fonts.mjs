#!/usr/bin/env node
// Usage: pnpm fonts
// Regenerates src/fonts.css from the @fontsource packages already installed in
// node_modules. One list below is the source of truth: the family, the package
// and which variable file to serve. Everything else (the family name, the
// weight range, the Latin unicode ranges) is read from each package, so a
// version bump is a `pnpm fonts` away.
//
// Only Latin and Latin Extended are emitted: enough for English and French,
// and every other subset stays on disk untouched. The browser fetches a face
// only when a page actually uses it, so an inactive type style costs nothing at
// runtime.

import { access, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MODULES = join(ROOT, "node_modules");
const SUBSETS = ["latin-ext", "latin"];

// The families the ten type styles in src/lib/typography.ts rely on, in the
// order they first appear. `axis` is the file variant: `full` keeps the extra
// axes (SOFT/WONK, CASL/MONO/slnt, INFM/BNCE), `opsz` keeps optical sizing,
// `wght` is weight only, and `static` is a fixed-weight family.
const FAMILIES = [
  // Herbarium
  { pkg: "geist", axis: "wght" },
  { pkg: "newsreader", axis: "opsz" },
  { pkg: "geist-mono", axis: "wght" },
  // Storybook
  { pkg: "nunito", axis: "wght" },
  { pkg: "fraunces", axis: "full" },
  // Field notes
  { pkg: "shantell-sans", axis: "full" },
  { pkg: "caveat", axis: "wght" },
  { pkg: "victor-mono", axis: "wght" },
  // Casual
  { pkg: "recursive", axis: "full" },
  // Poster
  { pkg: "bricolage-grotesque", axis: "opsz" },
  { pkg: "jetbrains-mono", axis: "wght" },
  // Library
  { pkg: "literata", axis: "opsz" },
  { pkg: "eb-garamond", axis: "wght" },
  { pkg: "courier-prime", axis: "static" },
  // Typewriter
  { pkg: "special-elite", axis: "static" },
  // Arcade
  { pkg: "space-grotesk", axis: "wght" },
  { pkg: "pixelify-sans", axis: "wght" },
  // Playground
  { pkg: "playpen-sans", axis: "wght" },
  { pkg: "baloo-2", axis: "wght" },
  // Easy reading
  { pkg: "atkinson-hyperlegible-next", axis: "wght" },
  { pkg: "atkinson-hyperlegible-mono", axis: "wght" },
];

const MODULE_PREFIX = { static: "@fontsource", variable: "@fontsource-variable" };

async function exists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

function weightRange(metadata, axis) {
  if (axis === "static") return metadata.weights;
  const wght = metadata.variable?.wght;
  if (!wght) throw new Error(`${metadata.id}: no wght axis in metadata.json`);
  return [`${wght.min} ${wght.max}`];
}

/** The @font-face blocks for one package, Latin Extended first as in fonts.css. */
async function facesFor({ pkg, axis }) {
  const kind = axis === "static" ? "static" : "variable";
  const moduleName = MODULE_PREFIX[kind];
  const dir = join(MODULES, moduleName, pkg);
  const metadata = JSON.parse(await readFile(join(dir, "metadata.json"), "utf8"));
  const unicode = JSON.parse(await readFile(join(dir, "unicode.json"), "utf8"));
  const family = kind === "variable" ? `${metadata.family} Variable` : metadata.family;
  const weights = weightRange(metadata, axis);
  const format = kind === "variable" ? "woff2-variations" : "woff2";
  const filesDir = `${moduleName}/${pkg}/files`;
  const faces = [];

  for (const subset of SUBSETS) {
    const range = unicode[subset];
    if (!range) throw new Error(`${pkg}: unicode.json has no "${subset}" subset`);

    const suffixes = kind === "variable" ? [`${axis}`] : weights.map((w) => `${w}`);
    for (const suffix of suffixes) {
      const file = `${pkg}-${subset}-${suffix}-normal.woff2`;
      const filePath = join(dir, "files", file);
      if (!(await exists(filePath))) {
        throw new Error(`${pkg}: missing files/${file} (is axis "${axis}" right?)`);
      }
      const weight = kind === "variable" ? weights[0] : suffix;
      faces.push(`/* ${pkg}-${subset}-${suffix}-normal */
@font-face {
  font-family: '${family}';
  font-style: normal;
  font-display: swap;
  font-weight: ${weight};
  src: url(../node_modules/${filesDir}/${file}) format('${format}');
  unicode-range: ${range};
}
`);
    }
  }

  return { family, faces };
}

const seen = new Set();
const families = [];
for (const entry of FAMILIES) {
  if (seen.has(entry.pkg)) continue;
  seen.add(entry.pkg);
  families.push(await facesFor(entry));
}

const header = `/* Herbarium — the interface fonts.

   Generated by \`pnpm fonts\` (scripts/fonts.mjs) from the @fontsource
   packages in node_modules. Do not edit this file by hand: change the list in
   the script and run \`pnpm fonts\`.

   Only the Latin and Latin Extended subsets are emitted, enough for English
   and French; other scripts fall back to the system fonts. Each face is
   downloaded only when a style actually uses it.

   Licences: SIL Open Font License 1.1 for every family except Special Elite,
   which is Apache-2.0. The full texts ship with each package
   (node_modules/@fontsource/<package>/LICENSE).
*/

`;

const css = header + families.flatMap((f) => f.faces).join("\n");
const out = join(ROOT, "src", "fonts.css");
await writeFile(out, css);

console.log(
  `fonts.css: ${families.length} families, ${families.reduce((n, f) => n + f.faces.length, 0)} faces, ${css.length} bytes`,
);
